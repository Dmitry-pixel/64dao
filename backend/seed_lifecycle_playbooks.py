def _rows():
    """Список (kind, key, contour, payload, sort) для upsert в fin_content."""
    rows = []
    for contour, lines in MATRIX.items():
        for line, (yin_text, oldyang_text) in lines.items():
            title = LINE_TITLES[line]
            rows.append((
                "action_package", f"line{line}_yin", contour,
                {"title": title, "text": yin_text}, line,
            ))
            rows.append((
                "action_package", f"line{line}_oldyang", contour,
                {"title": title, "text": oldyang_text}, line,
            ))
    return rows


async def main():
    rows = _rows()
    async with async_session_maker() as session:
        inserted = updated = 0
        for kind, key, contour, payload, sort in rows:
            existing = (
                await session.execute(
                    select(FinContent).where(
                        FinContent.kind == kind,
                        FinContent.key == key,
                        FinContent.contour == contour,
                    )
                )
            ).scalar_one_or_none()
            if existing is None:
                session.add(FinContent(
                    id=uuid.uuid4(), kind=kind, key=key,
                    contour=contour, payload=payload, sort=sort,
                ))
                inserted += 1
            else:
                existing.payload = payload
                existing.sort = sort
                updated += 1
        await session.commit()
        print(f"action_packages: вставлено {inserted}, обновлено {updated} (всего {len(rows)})")


if __name__ == "__main__":
    asyncio.run(main())
