async def main():
    async with async_session_maker() as session:
        # Удаляем все существующие стратегии
        await session.execute(delete(Strategy))
        await session.commit()
        print("Старые стратегии удалены.")

        # Вставляем 64 новых
        for n, name, combo, stage in HEXAGRAMS:
            s = Strategy(
                id=uuid.uuid4(),
                combination=combo,
                title=name,
                lifecycle_stage=stage,
                current_state={"combination": combo, "hex_name": name},
                is_published=False,
            )
            session.add(s)

        await session.commit()
        print(f"✓ Создано {len(HEXAGRAMS)} стратегий.")


if __name__ == "__main__":
    asyncio.run(main())
