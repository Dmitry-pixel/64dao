# -*- coding: utf-8 -*-
"""
Замки на таблицу вердиктов Метода 3.

Тесты фиксируют принятые решения и структурные инварианты, а не проверяют
расчёт. Жанр тот же, что у test_single_object_share_below_coverage_rejected:
поведение закреплено, чтобы его не изменили мимоходом.
"""
from app import m3_verdict as vd


def test_exit_family_has_no_reduced_override():
    """
    Решение владельца 15 августа: семейство exit переопределений для
    сокращённого режима не получает. Возражение было высказано и отклонено:
    в портфеле это продажа одной единицы из пяти, при одном направлении
    закрытие бизнеса, но формулировка верна по существу.

    Замок стоит здесь потому, что комментарий над VERDICTS_REDUCED задаёт
    критерий отбора: «только те ключи, где формулировка отвечает на вопрос,
    среди чего выбирать». По этому критерию ('exit', 'stable') выглядит
    очевидным кандидатом на шестую строку. Код приглашает сделать то, что
    решением запрещено, и ревизия этого не заметит.

    Снимать вместе с решением владельца, а не по образцу соседних строк.
    Разбор: 64dao_handoff_2026-08-15.md, раздел 1, пункт 4.
    """
    offenders = sorted(k for k in vd.VERDICTS_REDUCED if k[0] == "exit")
    assert offenders == [], (
        "Переопределение сокращённого режима для семейства exit: "
        f"{offenders}. Решение 15 августа их запрещает."
    )


def test_reduced_overrides_are_known_keys():
    """
    Каждое переопределение обязано иметь пару в базовой таблице.

    verdict_for берёт VERDICTS_REDUCED.get(key) и при промахе молча
    откатывается к базовой строке. Опечатка в ключе не падает и не
    печатается: переопределение просто не сработает, и заметить это можно
    только вычиткой отчёта.
    """
    unknown = sorted(k for k in vd.VERDICTS_REDUCED if k not in vd.VERDICTS)
    assert unknown == [], f"Ключи вне базовой таблицы: {unknown}"


def test_every_reachable_combination_has_verdict():
    """
    Каждая достижимая пара «зона + подвижность» обязана иметь вердикт.

    verdict_for обращается к VERDICTS[key] напрямую, без get. Пропущенная
    комбинация роняет сборку отчёта, а не печатает пустую строку, и упадёт
    у первого пользователя, чьё направление в неё попадёт.
    """
    stances = {z[0] for z in vd.ZONES.values()}
    missing = sorted(
        (s, m) for s in stances
        for m in ("target", "risk", "both", "stable")
        if (s, m) not in vd.VERDICTS
    )
    assert missing == [], f"Комбинации без вердикта: {missing}"


def test_verdicts_are_pairwise_distinct():
    """
    Таблица двумерна ровно затем, чтобы разные состояния расходились
    в формулировке: направления одной клетки получают разные вердикты по
    подвижности линий. Совпадение строки на двух разных ключах стирает
    различие, которое метод измеряет.

    Ожидается 28 ключей и 28 разных строк.

    Один дубль был: ('limited','stable') и ('exit','stable') несли дословно
    «Пересборка или выход». Найден вычиткой, а не тестом: проверки тогда
    ещё не существовало. Закрыт правкой текста exit+stable, limited+stable
    оставлен как есть — там средний рынок, и пересборка обоснована.
    """
    seen: dict[str, tuple] = {}
    collisions = []
    for key, text in vd.VERDICTS.items():
        if text in seen:
            collisions.append((text, seen[text], key))
        else:
            seen[text] = key
    assert collisions == [], f"Совпадающие вердикты: {collisions}"
