async def main():
    async with AsyncSessionLocal() as session:
        updated = skipped = 0
        for n, (essence, mistake) in sorted(PATTERNS.items()):
            combo = NUM_TO_COMBO[n]
            strat = await session.scalar(select(Strategy).where(Strategy.combination == combo))
            if strat is None:
                print(f"  ! #{n} {combo}: строки нет"); continue
            if strat.fin_pattern_essence or strat.fin_pattern_mistake:
                skipped += 1; continue     # не трогаем заполненное (вкл. эталоны 34/14)
            strat.fin_pattern_essence = essence
            strat.fin_pattern_mistake = mistake
            updated += 1
        await session.commit()
        print(f"fin_pattern: заполнено {updated}, пропущено (уже было) {skipped}")

if __name__ == "__main__":
    asyncio.run(main())
