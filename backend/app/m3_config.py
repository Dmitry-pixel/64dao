UPLOAD_DIR = os.environ.get("UPLOAD_DIR", "/var/www/64dao/uploads")
M3_CONFIG_FILE = Path(UPLOAD_DIR) / "m3_config.json"


def _normalise(cfg: dict) -> dict:
    """
    JSON не умеет целочисленные ключи: после сохранения конфига через админку
    industry_presets возвращается со строковыми ключами, и лукап по int молча
    уезжает в универсальный пресет — расчёт при этом не падает, а тихо врёт.
    Приводим ключи обратно к int на чтении.
    """
    presets = cfg.get("industry_presets") or {}
    cfg = dict(cfg)
    cfg["industry_presets"] = {int(k): v for k, v in presets.items()}
    cfg["universal_industry_id"] = int(cfg.get("universal_industry_id", UNIVERSAL_INDUSTRY_ID))
    return cfg


def read_m3_config() -> dict:
    """Актуальный конфиг: дефолты из кода, поверх — сохранённые переопределения."""
    return _normalise(read_json(M3_CONFIG_FILE, DEFAULT_M3_CONFIG))


def write_m3_config(data: dict) -> None:
    write_json(M3_CONFIG_FILE, data)


def industry_weights(industry_id: int | None, config: dict | None = None) -> dict[str, int]:
    """
    Веса шести линий для отрасли. Неизвестная отрасль -> универсальный пресет 18.

    Мульти-выбор (§7) на уровне ядра не разворачивается: вызывающий код передаёт
    уже разрешённый industry_id либо готовый словарь весов.
    """
    cfg = config or DEFAULT_M3_CONFIG
    presets = cfg["industry_presets"]
    universal = cfg["universal_industry_id"]
    fallback = presets.get(universal) or presets[str(universal)]

    preset = fallback
    if industry_id is not None:
        # Ключи могут прийти строками из JSON — проверяем оба варианта.
        preset = presets.get(industry_id) or presets.get(str(industry_id)) or fallback
    return {k: preset[k] for k in ("L1", "L2", "L3", "L4", "L5", "L6")}


def average_presets(industry_ids: list[int], config: dict | None = None) -> dict[str, int]:
    """
    Мульти-выбор областей (§7): среднее арифметическое пресетов, нормированное
    к 100 внутри каждой оси. Пустой список -> универсальный пресет.
    """
    cfg = config or DEFAULT_M3_CONFIG
    if not industry_ids:
        return industry_weights(None, cfg)

    picked = [industry_weights(i, cfg) for i in industry_ids]
    raw = {k: sum(p[k] for p in picked) / len(picked) for k in ("L1", "L2", "L3", "L4", "L5", "L6")}

    result: dict[str, int] = {}
    for axis in (("L1", "L2", "L3"), ("L4", "L5", "L6")):
        total = sum(raw[k] for k in axis)
        scaled = {k: raw[k] * 100.0 / total for k in axis}
        # Нормировка к целым со 100 в сумме: округляем, остаток отдаём наибольшему.
        rounded = {k: int(round(v)) for k, v in scaled.items()}
        drift = 100 - sum(rounded.values())
        if drift:
            top = max(axis, key=lambda k: scaled[k])
            rounded[top] += drift
        result.update(rounded)
    return result
