# -*- coding: utf-8 -*-
"""Блокировка кошелька пользователя на время списания.

Остаток оплаченных диагностик не хранится, а вычисляется: оплаченные
заказы x единиц на заказ минус уже привязанные диагностики (см.
routers/payments.paid_credits, pick_order). Два параллельных запроса
одного пользователя читали один и тот же остаток, оба видели «осталась
одна», и оба её тратили: двойное нажатие или две вкладки давали две
диагностики за одну оплату (аудит 2026-10-06, R002).

Решение: транзакционная advisory-блокировка PostgreSQL на пару
(пользователь, кошелёк). Второй запрос ждёт, пока первый закоммитит
привязку, и считает остаток уже с ней. Блокировка снимается сама в конце
транзакции (commit или rollback в get_db), отдельно отпускать её не нужно.

Почему не SELECT ... FOR UPDATE по заказам: у пользователя может не быть
ни одного заказа (списание с гранта), а блокировать нечего — гонка
остаётся. Advisory-блокировка не зависит от наличия строк.

Кошельки: "m12" — Методы 1 и 2, "m3" — Метод 3, "m4" — полный Метод 4.
У m3 и m4 общий заказ, но счётчики раздельные, поэтому и ключи разные.
"""
from __future__ import annotations

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

WALLETS = ("m12", "m3", "m4")


async def lock_wallet(db: AsyncSession, user_id, wallet: str) -> None:
    """Захватить блокировку кошелька до конца текущей транзакции."""
    if wallet not in WALLETS:
        raise ValueError(f"unknown wallet: {wallet}")
    await db.execute(
        text("SELECT pg_advisory_xact_lock(hashtextextended(:key, 0))"),
        {"key": f"wallet:{wallet}:{user_id}"},
    )
