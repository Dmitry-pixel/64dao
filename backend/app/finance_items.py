def _build() -> list[FinanceItem]:
    items: list[FinanceItem] = []
    for item_id, text in _RAW_ITEMS:
        block = int(item_id.split(".")[0])
        items.append(FinanceItem(
            item_id=item_id,
            block=block,
            block_title=BLOCKS[block]["title"],
            line_key=BLOCKS[block]["key"],
            text=text,
            reverse=item_id in REVERSE_ITEMS,
            veto=item_id in VETO_ITEMS,
        ))
    return items


FINANCE_ITEMS: list[FinanceItem] = _build()

# Быстрый доступ
ITEM_IDS: tuple[str, ...] = tuple(i["item_id"] for i in FINANCE_ITEMS)
ITEMS_BY_ID: dict[str, FinanceItem] = {i["item_id"]: i for i in FINANCE_ITEMS}
ITEMS_BY_BLOCK: dict[int, list[FinanceItem]] = {
    b: [i for i in FINANCE_ITEMS if i["block"] == b] for b in BLOCKS
}
