"""
Конфигурация анкеты финансовой функции (Спецификация §2).

Это ЛОГИКА скоринга (структура анкеты, реверсивность, вето), а не редактируемый
контент — поэтому живёт в коде, не в БД (см. план §0.5, §3.1).

6 блоков × 4 подвопроса = 24 пункта. Блок N → линия N (снизу вверх).
Реверсивные пункты: 1.3, 2.3, 3.3, 4.4, 5.3, 6.3.
Вето: 4.1.
"""
from typing import TypedDict


class FinanceItem(TypedDict):
    item_id: str
    block: int
    block_title: str
    line_key: str
    text: str
    reverse: bool
    veto: bool


# Заголовки блоков и семантический ключ линии (Спецификация §2, §4.1)
BLOCKS: dict[int, dict[str, str]] = {
    1: {"key": "processes",   "title": "Линия 1. Текущие финансовые процессы"},
    2: {"key": "systems",     "title": "Линия 2. Технологии и системы"},
    3: {"key": "team",        "title": "Линия 3. Навыки и возможности команды"},
    4: {"key": "leadership",  "title": "Линия 4. Поддержка руководства"},
    5: {"key": "environment", "title": "Линия 5. Внешние и смежные факторы"},
    6: {"key": "strategy",    "title": "Линия 6. Видение и стратегия трансформации"},
}

REVERSE_ITEMS: frozenset[str] = frozenset({"1.3", "2.3", "3.3", "4.4", "5.3", "6.3"})
VETO_ITEMS: frozenset[str] = frozenset({"4.1"})

# Ярлыки шкалы 1–4 (Спецификация §1)
SCALE_LABELS: dict[int, str] = {
    1: "Нет, совсем не так",
    2: "Скорее нет",
    3: "Скорее да",
    4: "Да, полностью соответствует",
}

