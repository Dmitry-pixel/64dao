REVERSE_ITEMS = frozenset({"1.3", "2.3", "3.3", "4.4", "5.3", "6.3"})
VETO_ITEMS = frozenset({"4.1"})
LINE_KEYS = ["processes", "systems", "team", "leadership", "environment", "strategy"]


def _blocks(titles: list[str]) -> dict[int, dict[str, str]]:
    return {
        i: {"key": k, "title": f"Линия {i}. {t}"}
        for i, (k, t) in enumerate(zip(LINE_KEYS, titles), start=1)
    }


def _items(raw: list[tuple[str, str]], blocks: dict) -> list[dict]:
    out = []
    for item_id, text in raw:
        b = int(item_id.split(".")[0])
        out.append({
            "item_id": item_id,
            "block": b,
            "block_title": blocks[b]["title"],
            "line_key": blocks[b]["key"],
            "text": text,
            "reverse": item_id in REVERSE_ITEMS,
            "veto": item_id in VETO_ITEMS,
        })
    return out


def _spec(key: str, title: str, block_titles: list[str],
          raw: list[tuple[str, str]]) -> ContourSpec:
    blocks = _blocks(block_titles)
    return ContourSpec(
        key=key,
        title=title,
        blocks=blocks,
        items=_items(raw, blocks),
        reverse_items=REVERSE_ITEMS,
        veto_items=VETO_ITEMS,
    )


