# -*- coding: utf-8 -*-
"""
Тексты зон под одиночный режим Метода 3 (kind zone_reduced).

Идемпотентно: повторный запуск вставляет 0 и НЕ перетирает правки из админки.
Требует миграцию 036.

Две зоны из девяти в сокращённом отчёте лгут прямым текстом:
  high_low «Сбор урожая»        — «источник денег для остального портфеля»;
  mid_high «Незавершённое ядро» — «останется одним из».
Остальные семь читаются нормально и своей версии не получают: резолюция
откатывается к kind zone (m3_service._zone_block).

СТАТУС ТЕКСТОВ: проект, требует чтения владельцем (план §6). Тон Метода 3
рассчитан на выбор МЕЖДУ направлениями; здесь выбор переведён во внутренний.

Запуск: docker compose exec -T backend python seed_m3_zone_reduced.py
"""
import asyncio

from sqlalchemy import select

from app.db import AsyncSessionLocal
import app.models        # обязателен: иначе NoReferencedTableError на flush
import app.m3_models     # noqa: F401
from app.m3_models import M3Content

HIGH_LOW_BODY = (
    "Конкурентная сила высокая, привлекательность рынка низкая. Позиция "
    "держится тем, что уже построено, а не тем, что рынок растёт: он и не "
    "растёт. Направление зарабатывает и продолжит зарабатывать какое-то "
    "время, но вложение в рост здесь дорого и малорезультативно.\n\n"
    "Рабочий режим: снимать отдачу, держать издержки, не наращивать долю. "
    "Куда направить высвобожденные деньги, эта диагностика не отвечает: "
    "сравнивать не с чем, направление одно. Вопрос ставится так — сколько "
    "времени у направления в текущей конфигурации и что вы успеете "
    "построить за это время рядом."
)

HIGH_LOW_MISTAKE = (
    "Устойчивая выручка читается как подтверждение, что с рынком всё в "
    "порядке, и в рост вкладываются там, где растут только затраты. "
    "Зеркальная ошибка не мягче: услышав «сбор урожая», перестают вкладывать "
    "вовсе, включая поддержание того, чем позиция держится."
)

MID_HIGH_BODY = (
    "Привлекательность рынка высокая, собственная сила средняя. Позиция не "
    "проиграна и не выиграна: она недособрана. Рынок даёт больше, чем "
    "направление сейчас берёт, и разрыв закрывается не временем, а работой "
    "по конкретным линиям — их видно в разборе ниже.\n\n"
    "Решений два, и оба честные: довести конкурентную силу до уровня рынка "
    "либо признать, что окно закроется без вас. Полумеры дороже обоих. "
    "Альтернативной стоимости, выраженной в других направлениях, у этого "
    "выбора сейчас нет: цена измеряется временем и деньгами, которые вы "
    "готовы положить в один объект, и тем, что произойдёт, если не положить."
)

MID_HIGH_MISTAKE = (
    "Высокая привлекательность читается как запас времени. Средняя сила на "
    "растущем рынке означает обратное: разрыв с теми, кто вкладывает сейчас, "
    "увеличивается каждый квартал — в том числе тогда, когда ваши "
    "собственные показатели растут."
)

ROWS = {
    # Название зоны не меняется: режим меняет разбор, а не карту.
    "high_low": ("Сбор урожая", HIGH_LOW_BODY, HIGH_LOW_MISTAKE),
    "mid_high": ("Незавершённое ядро", MID_HIGH_BODY, MID_HIGH_MISTAKE),
}


async def main() -> None:
    inserted = skipped = 0
    async with AsyncSessionLocal() as db:
        for key, (title, body, mistake) in ROWS.items():
            row = await db.scalar(select(M3Content).where(
                M3Content.kind == "zone_reduced",
                M3Content.key == key,
                M3Content.industry_id.is_(None),
            ))
            if row is not None:
                skipped += 1
                continue
            db.add(M3Content(kind="zone_reduced", key=key, industry_id=None,
                             title=title, body=body, mistake=mistake,
                             is_active=True))
            inserted += 1
        await db.commit()
    print("INSERTED=%d SKIPPED=%d" % (inserted, skipped))


if __name__ == "__main__":
    asyncio.run(main())
