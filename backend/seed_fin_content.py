def _rows():
    """Список (kind, key, payload, sort) для fin_content."""
    rows = []
    for i, (key, title, text, cond) in enumerate(TONALITY):
        rows.append(("tonality", key, {"title": title, "text": text, "condition": cond}, i))
    for i, (key, title, text) in enumerate(QUADRANT):
        rows.append(("quadrant", key, {"title": title, "text": text}, i))
    for i, (code, name, lower, upper) in enumerate(TRIGRAMS):
        rows.append(("trigram", f"{code}_lower", {"title": name, "text": lower}, i * 2))
        rows.append(("trigram", f"{code}_upper", {"title": name, "text": upper}, i * 2 + 1))
    for i, (key, cond, text) in enumerate(TENSION_RULES):
        rows.append(("tension_rule", key, {"text": text, "condition": cond}, i))
    for i, (key, title, text) in enumerate(ACTION_PACKAGES_YIN):
        rows.append(("action_package", key, {"title": title, "text": text}, i))
    return rows


async def main():
    async with async_session_maker() as session:
        inserted = updated = 0
        for kind, key, payload, sort in _rows():
            existing = (
                await session.execute(
                    select(FinContent).where(FinContent.kind == kind, FinContent.key == key)
                )
            ).scalar_one_or_none()
            if existing is None:
                session.add(FinContent(id=uuid.uuid4(), kind=kind, key=key, payload=payload, sort=sort))
                inserted += 1
            else:
                existing.payload = payload
                existing.sort = sort
                updated += 1
        await session.commit()
        print(f"fin_content: вставлено {inserted}, обновлено {updated}")

        # fin_pattern_* на strategies (UPDATE по combination; строки не создаём)
        p_upd = p_missing = 0
        for combo, (essence, mistake) in FIN_PATTERNS.items():
            strat = (
                await session.execute(select(Strategy).where(Strategy.combination == combo))
            ).scalar_one_or_none()
            if strat is None:
                p_missing += 1
                print(f"  ! strategy {combo} не найдена — fin_pattern не записан")
                continue
            strat.fin_pattern_essence = essence
            strat.fin_pattern_mistake = mistake
            p_upd += 1
        await session.commit()
        print(f"fin_pattern_*: обновлено {p_upd}, пропущено (нет строки) {p_missing}")


if __name__ == "__main__":
    asyncio.run(main())
