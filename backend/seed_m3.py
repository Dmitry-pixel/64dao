async def seed_hexagrams(db) -> int:
    """64 строки из единого источника истины app.hexagrams."""
    existing = {h.code for h in (await db.execute(select(M3Hexagram))).scalars()}
    added = 0
    for num, name, code in HEXAGRAM_LIST:
        if code in existing:
            continue
        db.add(M3Hexagram(code=code, kw_number=num, name_64dao=name))
        added += 1
    return added


async def seed_weights(db) -> int:
    rows = {w.industry_id: w for w in (await db.execute(select(M3Weight))).scalars()}
    touched = 0
    for iid, preset in INDUSTRY_PRESETS.items():
        w = rows.get(iid)
        if w is None:
            w = M3Weight(industry_id=iid)
            db.add(w)
        w.name = preset["name"]
        for n in range(1, 7):
            setattr(w, f"w_l{n}", preset[f"L{n}"])
        touched += 1
    return touched


async def seed_items(db) -> int:
    """
    Общий слой, версия 1. Отраслевых переопределений на старте ноль —
    писать 252 формулировки вперёд наугад бессмысленно, пилот сам покажет,
    что промахивается (§13).
    """
    rows = {
        (i.code, i.industry_id, i.item_version): i
        for i in (await db.execute(select(M3Item))).scalars()
    }
    touched = 0
    for it in ITEMS:
        key = (it["code"], None, 1)
        row = rows.get(key)
        if row is None:
            db.add(M3Item(
                code=it["code"], block=it["block"], number=it["number"],
                line=it["line"], text=it["text"], is_reverse=it["is_reverse"],
                industry_id=None, item_version=1, is_active=True,
            ))
        else:
            row.text = it["text"]
            row.line = it["line"]
            row.is_reverse = it["is_reverse"]
        touched += 1
    return touched


async def seed_content(db) -> int:
    rows = {
        (c.kind, c.key, c.industry_id): c
        for c in (await db.execute(select(M3Content))).scalars()
    }
    touched = 0
    for b in CONTENT_BLOCKS:
        row = rows.get((b["kind"], b["key"], None))
        if row is None:
            row = M3Content(kind=b["kind"], key=b["key"], industry_id=None)
            db.add(row)
        row.title, row.body, row.mistake = b["title"], b["body"], b["mistake"]
        row.is_active = True
        touched += 1
    return touched


async def seed_hints(db) -> int:
    rows = {
        (h.industry_id, h.item_code): h
        for h in (await db.execute(select(M3Hint))).scalars()
    }
    touched = 0
    for h in HINTS:
        row = rows.get((h["industry_id"], h["item_code"]))
        if row is None:
            row = M3Hint(industry_id=h["industry_id"], item_code=h["item_code"])
            db.add(row)
        row.text = h["text"]
        touched += 1
    return touched


async def main() -> None:
    async with AsyncSessionLocal() as db:
        hexes = await seed_hexagrams(db)
        weights = await seed_weights(db)
        items = await seed_items(db)
        content = await seed_content(db)
        hints = await seed_hints(db)
        await db.commit()

    print(f"m3_hexagrams: +{hexes}")
    print(f"m3_weights:    {weights}")
    print(f"m3_items:      {items}")
    print(f"m3_content:    {content}")
    print(f"m3_hints:      {hints}")

    if content < 31:
        print("ВНИМАНИЕ: блоков контента меньше 31 — разбор соберётся неполным")


if __name__ == "__main__":
    asyncio.run(main())
