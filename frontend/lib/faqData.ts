export function buildFaqSchema(priceLabel: string) {
  return {
    '@type': 'FAQPage',
    '@id': 'https://64dao.ru/#faq',
    mainEntity: buildFaqData(priceLabel).map((item) => ({
      '@type': 'Question',
      name: item.q,
      acceptedAnswer: {
        '@type': 'Answer',
        text: item.a,
      },
    })),
  }
}
